#define KEYS_ARG_EXTEND        UINT16_C(1)
#define KEYS_ARG_UNIMPLEMENTED UINT16_C(2)
#define KEYS_ARG_BLOCK         UINT16_C(4)
#define KEYS_ARG_SIDE_BY_SIDE  UINT16_C(8) /* also clear views to right */
