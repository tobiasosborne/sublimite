#define KEYS_ARG_SELECT        UINT16_C(32)
#define KEYS_ARG_CASE_SENSITIVE UINT16_C(64)
#define KEYS_ARG_PREFER_HIDE   UINT16_C(128)
#define KEYS_ARG_NO_MOVE       UINT16_C(256)
#define KEYS_ARG_SINGLE_LINE   UINT16_C(512)

typedef enum keys_chord {
    KEYS_CHORD_NONE, KEYS_CHORD_K, KEYS_CHORD_J, KEYS_CHORD_COUNT
} keys_chord;

typedef struct keys_args {
    uint16_t flags;
    int16_t value; /* INSERT: Unicode ASCII; column +/-1; scroll +/-1;
                   * group/tab: zero-based; layout: Linux digit preset;
                   * fold: level; font: +/-1; CHORD: next keys_chord. */
    uint8_t chord; /* namespace of this stroke; NONE = standalone/prefix */
} keys_args;

typedef struct keys_binding {
    uint16_t modifiers; /* PLAT_MOD_*; excludes lock bits */
    uint32_t keysym;    /* XKB_KEY_*; canonical ASCII lowercase */
    keys_action action;
    keys_args args;
} keys_binding;

/* Zero initialize once per input owner. Reset on focus/keymap/view changes.
 * No timeout/clock hidden in lookup; caller may reset on its own timeout. */
typedef struct keys_state { uint8_t chord; } keys_state;
typedef enum keys_result {
    KEYS_NONE, KEYS_MATCH, KEYS_PREFIX, KEYS_CANCELLED, KEYS_ERR_ARG
} keys_result;

void keys_reset(keys_state *state); /* NULL is allowed */
/* Read-only table sorted by (args.chord, modifiers, keysym). No allocation.
 * Returned storage has process lifetime; count is optional. */
const keys_binding *keys_defaults(size_t *count);
/* O(log n), no allocation. out is cleared except on MATCH/PREFIX.
 * Lock bits ignored; unknown modifier bits and AltGr never match shortcuts.
 * ASCII uppercase, ISO_Left_Tab, keypad navigation, and US shifted shortcut
 * punctuation are canonicalized. No arbitrary layout transliteration.
 * Bare modifier presses preserve a pending chord. A mismatched second stroke
 * consumes/cancels the chord (no standalone replay); Escape cancels it too.
 * A corrupt chord byte resets to NONE before looking up the current stroke.
 * NONE permits normal text; PREFIX/CANCELLED consume input; MATCH may carry
 * UNIMPLEMENTED, in which case the caller must consume without editing. */
keys_result keys_lookup(keys_state *state, uint32_t keysym, uint16_t modifiers,
                        const keys_binding **out);

