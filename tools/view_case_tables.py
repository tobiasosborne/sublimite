#!/usr/bin/env python3
"""Generate the locale-independent mappings used by Default/transform.py.

Values are (G) from Python's Unicode database, the same str.upper/str.lower
semantics as the installed Sublime command source. Array capacity is computed
from maximum encoded mapping length; no hand-picked expansion reserve.
"""
import unicodedata
from pathlib import Path

rows = []
for cp in range(0x110000):  # Unicode scalar space: U+0000 through U+10FFFF
    ch = chr(cp)
    upper, lower = ch.upper(), ch.lower()
    if upper != ch or lower != ch:
        rows.append((cp, upper.encode('utf8'), lower.encode('utf8')))
maximum = max(len(v) for _, up, low in rows for v in (up, low))
path = Path('src/view/case_tables.h')
with path.open('w') as f:
    f.write('/* Generated by tools/view_case_tables.py from Python Unicode '+unicodedata.unidata_version+'.\n'
            ' * (G) Capacity = max UTF-8 length of str.upper/str.lower over scalar space. */\n')
    f.write('typedef struct view_case_mapping { uint32_t cp; uint8_t upper_len, lower_len;\n')
    f.write('    uint8_t upper['+str(maximum)+'], lower['+str(maximum)+']; } view_case_mapping;\n')
    f.write('static const view_case_mapping view_case_mappings[] = {\n')
    for cp, up, low in rows:
        f.write('    {0x%x, %d, %d, {%s}, {%s}},\n' % (cp, len(up), len(low), ','.join('0x%02x' % b for b in up), ','.join('0x%02x' % b for b in low)))
    f.write('};\n')

    properties = {'Cased': [], 'Case_Ignorable': []}
    for line in Path('vendor/ucd/DerivedCoreProperties.txt').read_text().splitlines():
        line = line.split('#', 1)[0].strip()
        if not line or ';' not in line:
            continue
        span, prop = (part.strip() for part in line.split(';', 1))
        if prop not in properties:
            continue
        parts = span.split('..')
        lo, hi = int(parts[0], 16), int(parts[-1], 16)
        # Keep the generator's Python Unicode repertoire. The vendored
        # derived properties provide the exact case context for those scalars.
        for cp in range(lo, hi + 1):
            if unicodedata.category(chr(cp)) != 'Cn':
                properties[prop].append(cp)
    for prop, name in [('Cased', 'cased'), ('Case_Ignorable', 'case_ignorable')]:
        ranges = []
        for cp in sorted(properties[prop]):
            if ranges and ranges[-1][1] + 1 == cp:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
        f.write('/* Case context from vendored DerivedCoreProperties, Python repertoire. */\n')
        f.write('static const uint32_t view_'+name+'[][2] = {\n')
        for lo, hi in ranges:
            f.write('    {0x%x, 0x%x},\n' % (lo, hi))
        f.write('};\n')

    for name, categories in [('word_alpha', 'LM'), ('word_digit', 'N')]:
        ranges = []
        for cp in range(0x110000):  # Unicode scalar space, as above
            if unicodedata.category(chr(cp))[0] not in categories:
                continue
            if ranges and ranges[-1][1] + 1 == cp:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
        f.write('/* Word classes from Python Unicode categories '+categories+'. */\n')
        f.write('static const uint32_t view_'+name+'[][2] = {\n')
        for lo, hi in ranges:
            f.write('    {0x%x, 0x%x},\n' % (lo, hi))
        f.write('};\n')
