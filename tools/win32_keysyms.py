#!/usr/bin/env python3
"""Generate Win32 non-character VK and Unicode-to-legacy-XKB tables.

VK names come from the Windows SDK winuser.h virtual-key definitions. Values
come solely from our vendored xkbcommon-keysyms.h; no host XKB dependency.
Run in the repository root: python3 tools/win32_keysyms.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / 'vendor/xkbcommon/xkbcommon-keysyms.h').read_text()
values = dict(re.findall(r'^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+)', source, re.M))
pairs = '''BACK BackSpace
TAB Tab
CLEAR Clear
RETURN Return
PAUSE Pause
CAPITAL Caps_Lock
ESCAPE Escape
PRIOR Prior
NEXT Next
END End
HOME Home
LEFT Left
UP Up
RIGHT Right
DOWN Down
SELECT Select
PRINT Print
EXECUTE Execute
SNAPSHOT Print
INSERT Insert
DELETE Delete
HELP Help
LWIN Super_L
RWIN Super_R
APPS Menu
MULTIPLY KP_Multiply
ADD KP_Add
SEPARATOR KP_Separator
SUBTRACT KP_Subtract
DECIMAL KP_Decimal
DIVIDE KP_Divide
NUMLOCK Num_Lock
SCROLL Scroll_Lock
LSHIFT Shift_L
RSHIFT Shift_R
LCONTROL Control_L
RCONTROL Control_R
LMENU Alt_L
RMENU Alt_R
BROWSER_BACK XF86Back
BROWSER_FORWARD XF86Forward
BROWSER_REFRESH XF86Refresh
BROWSER_STOP XF86Stop
BROWSER_SEARCH XF86Search
BROWSER_FAVORITES XF86Favorites
BROWSER_HOME XF86HomePage
VOLUME_MUTE XF86AudioMute
VOLUME_DOWN XF86AudioLowerVolume
VOLUME_UP XF86AudioRaiseVolume
MEDIA_NEXT_TRACK XF86AudioNext
MEDIA_PREV_TRACK XF86AudioPrev
MEDIA_STOP XF86AudioStop
MEDIA_PLAY_PAUSE XF86AudioPlay
LAUNCH_MAIL XF86Mail
LAUNCH_MEDIA_SELECT XF86AudioMedia
LAUNCH_APP1 XF86Launch0
LAUNCH_APP2 XF86Launch1
SLEEP XF86Sleep'''
entries = [line.split() for line in pairs.splitlines()]
entries += [(f'F{i}', f'F{i}') for i in range(1, 25)]
entries += [(f'NUMPAD{i}', f'KP_{i}') for i in range(10)]
legacy = {}
for name, number, scalar in re.findall(r'^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+)\s+/\* U\+([0-9a-fA-F]+)', source, re.M):
    value, code = int(number, 16), int(scalar, 16)
    if 0x100 <= value < 0x10000:
        legacy.setdefault(code, value)
lines = ['/* Generated by tools/win32_keysyms.py; do not edit. */',
         '#ifndef EDIT_WIN32_KEYSYMS_H', '#define EDIT_WIN32_KEYSYMS_H',
         'static const uint32_t win32_vk_keysyms[256] = {']
for vk, name in entries:
    lines.append(f'    [VK_{vk}] = {values[name]}u, /* {name} */')
lines += ['};', 'static const struct { uint32_t scalar, keysym; } win32_legacy_keysyms[] = {']
for scalar, value in sorted(legacy.items()):
    lines.append(f'    {{0x{scalar:04x}u, 0x{value:04x}u}},')
lines += ['};', '#endif', '']
(root / 'src/win32/keysyms.h').write_text('\n'.join(lines))
