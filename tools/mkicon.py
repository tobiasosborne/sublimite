"""Generate the sublimité app icon (edit-36b3): tools/sublimite.svg and tools/icons/sublimite-N.png.

The icon is workup 04 of docs/design/icon-workups-2026-10-26: a Bodoni Moda Italic é on the
editor's dark tile, the accent in Mint-Y-Dark-Aqua. The outputs are committed; the font is not
in the repo, so regenerate only when the design changes:

    FONTCONFIG_FILE=<fonts.conf with a <dir> holding BodoniModa-Italic[opsz,wght].ttf> python3 tools/mkicon.py

(github.com/google/fonts, ofl/bodonimoda; OFL, no reserved name). Needs pycairo only.
Colours: tile #222226 = Mint-Y-Dark wm_bg (the dark theme since edit-29y2); cream #efeae0 =
the title-font paper; accent #1f9ede = Mint-Y-Dark-Aqua accent_color. Coordinates are drawing
values on a 256-unit square, not budgets.
"""
import os, math
import cairo

TILE, CREAM, ACCENT = "#222226", "#efeae0", "#1f9ede"
FAMILY = "Bodoni Moda"
HERE = os.path.dirname(os.path.abspath(__file__))

# Per size: tile inset, corner radius, e weight, e ink height and centre, accent height and centre.
# 256 is the scalable design; the bitmaps trade margin and hairlines for size and weight so the
# e keeps its thin strokes visible on a 16-48 px panel.
TUNING = {
    256: dict(inset=8, radius=52, bold=False, e=(124, 122, 152), acute=(46, 152, 58)),
    48:  dict(inset=5, radius=48, bold=False, e=(140, 122, 156), acute=(52, 154, 52)),
    32:  dict(inset=4, radius=46, bold=True,  e=(148, 122, 158), acute=(56, 156, 50)),
    24:  dict(inset=3, radius=44, bold=True,  e=(156, 120, 160), acute=(60, 158, 46)),
    16:  dict(inset=0, radius=40, bold=True,  e=(166, 118, 168), acute=(62, 162, 50)),
}

def rgb(h):
    h = h.lstrip("#"); return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))

def rrect(cr, inset, r):
    x = y = inset; w = h = 256 - 2 * inset
    cr.new_sub_path()
    cr.arc(x + w - r, y + r, r, -math.pi / 2, 0); cr.arc(x + w - r, y + h - r, r, 0, math.pi / 2)
    cr.arc(x + r, y + h - r, r, math.pi / 2, math.pi); cr.arc(x + r, y + r, r, math.pi, 3 * math.pi / 2)
    cr.close_path()

def glyph_path(cr, ch, bold, height, cx, cy):
    """Leave the glyph's outline as the current path, ink box `height` tall centred on (cx, cy)."""
    cr.save()
    cr.select_font_face(FAMILY, cairo.FONT_SLANT_ITALIC, cairo.FONT_WEIGHT_BOLD if bold else cairo.FONT_WEIGHT_NORMAL)
    cr.set_font_size(100); cr.new_path(); cr.move_to(0, 0); cr.text_path(ch)
    x0, y0, x1, y1 = cr.path_extents(); path = cr.copy_path(); cr.new_path()
    s = height / (y1 - y0)
    cr.translate(cx - (x0 + x1) / 2 * s, cy - (y0 + y1) / 2 * s); cr.scale(s, s)
    cr.append_path(path); cr.restore()

def draw(cr, t):
    rrect(cr, t["inset"], t["radius"]); cr.set_source_rgb(*rgb(TILE)); cr.fill()
    glyph_path(cr, "e", t["bold"], *t["e"]); cr.set_source_rgb(*rgb(CREAM)); cr.fill()
    glyph_path(cr, "´", t["bold"], *t["acute"]); cr.set_source_rgb(*rgb(ACCENT)); cr.fill()

def svg_d(path):
    out = []
    for kind, pts in path:
        p = " ".join(f"{v:.2f}".rstrip("0").rstrip(".") for v in pts)
        out.append({cairo.PATH_MOVE_TO: "M", cairo.PATH_LINE_TO: "L",
                    cairo.PATH_CURVE_TO: "C", cairo.PATH_CLOSE_PATH: "Z"}[kind] + p)
    return "".join(out)

def write_svg(t):
    scratch = cairo.Context(cairo.ImageSurface(cairo.FORMAT_ARGB32, 1, 1))
    rrect(scratch, t["inset"], t["radius"]); tile = svg_d(scratch.copy_path()); scratch.new_path()
    glyph_path(scratch, "e", t["bold"], *t["e"]); e = svg_d(scratch.copy_path()); scratch.new_path()
    glyph_path(scratch, "´", t["bold"], *t["acute"]); acute = svg_d(scratch.copy_path())
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">\n'
           '  <!-- Generated by tools/mkicon.py (edit-36b3): Bodoni Moda Italic é (OFL) as paths;\n'
           '       colours are the Mint-Y-Dark surface, cream and aqua accent named there. -->\n'
           '  <title>sublimité</title>\n'
           f'  <path fill="{TILE}" d="{tile}"/>\n'
           f'  <path fill="{CREAM}" d="{e}"/>\n'
           f'  <path fill="{ACCENT}" d="{acute}"/>\n'
           '</svg>\n')
    with open(os.path.join(HERE, "sublimite.svg"), "w") as f: f.write(svg)

def write_png(px, t):
    img = cairo.ImageSurface(cairo.FORMAT_ARGB32, px, px)
    cr = cairo.Context(img); cr.scale(px / 256, px / 256); draw(cr, t)
    os.makedirs(os.path.join(HERE, "icons"), exist_ok=True)
    img.write_to_png(os.path.join(HERE, "icons", f"sublimite-{px}.png"))

if __name__ == "__main__":
    write_svg(TUNING[256])
    for px in (48, 32, 24, 16): write_png(px, TUNING[px])
    print("wrote tools/sublimite.svg and tools/icons/sublimite-{16,24,32,48}.png")
