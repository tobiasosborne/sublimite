#!/usr/bin/env python3
"""Generate allocation-free keysym lookup tables from the pinned header only."""
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "vendor/xkbcommon/xkbcommon-keysyms.h"
OUTPUT = ROOT / "src/keys/keysym_names.h"


def generate():
    entries = [(name, int(value, 16)) for name, value in re.findall(
        r"^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+)", HEADER.read_text(), re.M)]
    if not entries or len({name for name, _ in entries}) != len(entries):
        raise ValueError("missing or duplicate keysym definitions")
    # Canonical aliases follow header declaration order, as in libxkbcommon.
    canonical = {}
    groups = {}
    for name, value in entries:
        canonical.setdefault(value, name)
        groups.setdefault(name.lower(), []).append((name, value))
    # Non-letter collisions have no promised lowercase winner in XKB. Preserve
    # the pinned libxkbcommon 1.6.0 winners; the Linux oracle checks every row.
    collision_winners = {
        "dead_i": "dead_I", "dead_o": "dead_O", "dead_schwa": "dead_SCHWA",
        "kana_ya": "kana_YA", "kana_yo": "kana_YO", "kana_tsu": "kana_TSU",
    }
    folded = {}
    for name, group in groups.items():
        winner = min(group, key=lambda row: sum(c.isupper() for c in row[0]))
        if name in collision_winners:
            winner = next(row for row in group if row[0] == collision_winners[name])
        folded[name] = winner[1]
    entries.sort(key=lambda row: (row[0].lower(), row[0]))
    indices = {name: index for index, (name, _) in enumerate(entries)}
    lines = [
        "/* generated by tools/keysymgen.py from vendor/xkbcommon/xkbcommon-keysyms.h, do not edit */",
        "#ifndef EDIT_KEYS_KEYSYM_NAMES_H", "#define EDIT_KEYS_KEYSYM_NAMES_H",
        "#include <stdint.h>",
        f'#define KEYS_KEYSYM_NAME_CAP sizeof("{max((name for name, _ in entries), key=len)}")',
        "typedef struct keys_keysym_entry {",
        "    const char *name;",
        "    uint32_t value, folded;",
        "} keys_keysym_entry;",
        "/* Sorted by ASCII-folded name, then original name. */",
        "static const keys_keysym_entry keys_keysym_names[] = {",
    ]
    for name, value in entries:
        lines.append(f'    {{"{name}", 0x{value:08x}u, 0x{folded[name.lower()]:08x}u}},')
    lines += ["};", "/* Canonical name indices sorted by numeric keysym. */",
              "static const uint16_t keys_keysym_by_value[] = {"]
    # (P) uint16_t index capacity derives from its bit width; fail on growth.
    if len(entries) > 1 << 16:
        raise ValueError("keysym index no longer fits uint16_t")
    for value, name in sorted(canonical.items()):
        lines.append(f"    {indices[name]}u, /* 0x{value:08x}: {name} */")
    return "\n".join(lines + ["};", "#endif", ""])


if __name__ == "__main__":
    result = generate()
    if sys.argv[1:] == ["--check"]:
        if OUTPUT.read_text() != result:
            sys.exit("keysym_names.h is stale; run tools/keysymgen.py")
    elif sys.argv[1:]:
        sys.exit("usage: tools/keysymgen.py [--check]")
    else:
        OUTPUT.write_text(result)
